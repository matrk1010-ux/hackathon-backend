def main():
    if not SELLER_EMAIL:
        raise SystemExit("SEED_SELLER_EMAIL を設定してください（既存ユーザーのメール）。")
    print(f"投入先: {BASE_URL} / 出品者: {SELLER_EMAIL}")
    success, failed = 0, 0
    for i, (title, category, price, description) in enumerate(PRODUCTS):
        condition = CONDITIONS[i % len(CONDITIONS)]
        payload = {
            "title": title,
            "description": description,
            "price": price,
            "category": category,
            "condition": condition,
            "image_url": f"https://picsum.photos/seed/uttc{i}/600/600",
        }
        try:
            res = requests.post(
                f"{BASE_URL}/products/",
                json=payload,
                params={"seller_email": SELLER_EMAIL},
                timeout=30,
            )
            if res.status_code in (200, 201):
                success += 1
                print(f"[OK] {title} ({category} / {condition} / ¥{price})")
            else:
                failed += 1
                print(f"[NG {res.status_code}] {title} -> {res.text[:120]}")
        except Exception as e:
            failed += 1
            print(f"[ERR] {title} -> {e}")
        time.sleep(0.2)  # embedding生成があるので軽く間隔を空ける

    print(f"\n完了: 成功 {success} / 失敗 {failed} / 合計 {len(PRODUCTS)}")


if __name__ == "__main__":
    main()
