# ==================== マスタ値（ai.py と一致させる） ====================
# ゲートの「新品」判定に使う状態ラベル
NEW_CONDITION = "新品・未使用"

# 説明文に含まれていたら「新品の主張」とみなす語（フォームが新品でなくても弱く後押し）
NEW_KEYWORDS = ["新品", "未開封", "未使用", "シュリンク", "新品同様", "未開封品"]

# ==================== スコア配点（1出品あたり 0〜90） ====================
# 出品スコア = ( ① + ③ ) × ( 1 + CYCLE_BOOST × ②係数 )
# 根拠(① または ③)が無ければ 0。基礎点は撤廃し、点数を根拠の量に比例させる。

# ① 同一商品の大量出品（最大点と閾値）。誤検知を抑えるため厳格化（5個から/10個で満点）。
DUP_MAX_SCORE = 30.0
DUP_MIN_COUNT = 5       # これ以上で加点開始（この出品を含む総個数）
DUP_FULL_COUNT = 10     # これ以上で満点
# 「同一商品」とみなす embedding コサイン類似度のしきい値（既知リスク: 巻違いシリーズも高類似）
SAME_PRODUCT_SIM = 0.92

# ② 新品出品サイクル（直近の新品出品頻度）
# 断捨離で新品を一気に出す一般ユーザーを誤検知しないため、単独では加点しない。
# ①③の根拠(core)を裏付ける「増幅係数(0〜1)」として使い、閾値もかなり厳しめにする。
CYCLE_WINDOW_DAYS = 7    # 集計する直近日数
CYCLE_MIN_COUNT = 8      # これ未満は増幅なし（断捨離の一括出品を素通りさせる）
CYCLE_FULL_COUNT = 20    # これ以上で増幅最大
CYCLE_BOOST = 0.5        # core(①+③) を最大 1.5 倍まで増幅

# ③ 定価超え × 確信度
PRICE_MAX_SCORE = 30.0
PRICE_RATIO_MIN = 1.2   # 定価のこの倍未満は加点しない
PRICE_RATIO_FULL = 2.0  # この倍以上で満点（確信度を掛ける前）
PRICE_MIN_CONFIDENCE = 0.5  # これ未満の確信度は信用せず加点しない

# ==================== 累積スコアの蓄積（減衰） ====================
DECAY_HALF_LIFE_DAYS = 30.0  # この日数で50%に減衰

# ==================== 段階ペナルティの閾値（累積スコア） ====================
STAGE1_THRESHOLD = 100.0  # 警告＋買い手向けバッジ
STAGE2_THRESHOLD = 200.0  # 新規出品ブロック＋既存も公開導線から非表示


def stage_for_score(score: float) -> int:
    """減衰後の累積スコアから段階(0/1/2)を返す。"""
    if score >= STAGE2_THRESHOLD:
        return 2
    if score >= STAGE1_THRESHOLD:
        return 1
    return 0
